import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsEmail,
  IsEnum,
  IsJWT,
  IsOptional,
  IsString,
  IsTimeZone,
  Length,
  Matches,
  MaxLength,
} from 'class-validator';
import { Transform } from 'class-transformer';
import { ClientPlatform } from '../../common/enums';
import { Sanitize } from '../../common/utils/sanitize';
import { UserResponseDto } from '../../users/dto/user.dto';

const PASSWORD_RULE = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d).{8,128}$/;

/** Optional device info sent by web/mobile clients; enables per-device session management. */
export class DeviceInfoDto {
  @ApiPropertyOptional({ description: 'Stable device identifier generated by the client app', example: 'b7a0c1f2-android' })
  @IsOptional()
  @IsString()
  @MaxLength(191)
  deviceId?: string;

  @ApiPropertyOptional({ example: 'Pixel 9 Pro' })
  @IsOptional()
  @Sanitize()
  @IsString()
  @MaxLength(191)
  deviceName?: string;

  @ApiPropertyOptional({ enum: ClientPlatform, default: ClientPlatform.WEB })
  @IsOptional()
  @IsEnum(ClientPlatform)
  platform?: ClientPlatform;
}

export class RegisterDto extends DeviceInfoDto {
  @ApiProperty({ example: 'Priya' })
  @Sanitize()
  @IsString()
  @Length(1, 100)
  firstName: string;

  @ApiPropertyOptional({ example: 'Sharma' })
  @IsOptional()
  @Sanitize()
  @IsString()
  @MaxLength(100)
  lastName?: string;

  @ApiProperty({ example: 'owner@slinggroups.com' })
  @Transform(({ value }: { value: unknown }) => (typeof value === 'string' ? value.trim().toLowerCase() : value))
  @IsEmail()
  @MaxLength(191)
  email: string;

  @ApiProperty({ example: 'Str0ngPassw0rd', description: '8-128 chars, upper + lower case and a digit' })
  @Matches(PASSWORD_RULE, { message: 'password must be 8-128 characters with upper case, lower case and a digit' })
  password: string;

  @ApiPropertyOptional({ example: 'Asia/Kolkata' })
  @IsOptional()
  @IsTimeZone()
  timezone?: string;
}

export class LoginDto extends DeviceInfoDto {
  @ApiProperty({ example: 'owner@slinggroups.com' })
  @Transform(({ value }: { value: unknown }) => (typeof value === 'string' ? value.trim().toLowerCase() : value))
  @IsEmail()
  email: string;

  @ApiProperty({ example: 'Str0ngPassw0rd' })
  @IsString()
  @Length(1, 128)
  password: string;
}

export class RefreshTokenDto {
  @ApiProperty({ description: 'Refresh token returned by login/refresh. Rotated on every use.' })
  @IsJWT()
  refreshToken: string;
}

export class ChangePasswordDto {
  @ApiProperty() @IsString() currentPassword: string;

  @ApiProperty()
  @Matches(PASSWORD_RULE, { message: 'newPassword must be 8-128 characters with upper case, lower case and a digit' })
  newPassword: string;
}

export class PushTokenDto {
  @ApiProperty({ description: 'FCM/APNs device push token' })
  @IsString()
  @MaxLength(500)
  pushToken: string;
}

export class TokenPairDto {
  @ApiProperty() accessToken: string;
  @ApiProperty() refreshToken: string;
  @ApiProperty({ example: 'Bearer' }) tokenType: string;
  @ApiProperty({ description: 'Access token lifetime in seconds', example: 900 }) expiresIn: number;
  @ApiProperty({ description: 'Refresh token lifetime in seconds', example: 2592000 }) refreshExpiresIn: number;
}

export class AuthResponseDto {
  @ApiProperty({ type: UserResponseDto }) user: UserResponseDto;
  @ApiProperty({ type: TokenPairDto }) tokens: TokenPairDto;
  @ApiProperty({ example: '7d4c...' }) sessionId: string;
}

export class SessionResponseDto {
  @ApiProperty() id: string;
  @ApiPropertyOptional({ nullable: true }) deviceId: string | null;
  @ApiPropertyOptional({ nullable: true }) deviceName: string | null;
  @ApiProperty({ enum: ClientPlatform }) platform: ClientPlatform;
  @ApiPropertyOptional({ nullable: true }) userAgent: string | null;
  @ApiPropertyOptional({ nullable: true }) ipAddress: string | null;
  @ApiPropertyOptional({ nullable: true }) lastUsedAt: Date | null;
  @ApiProperty() createdAt: Date;
  @ApiProperty() expiresAt: Date;
  @ApiProperty() current: boolean;
}
